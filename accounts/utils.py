"""Формулы доверия к пользователю: вес его голоса при оценке грибных мест.

Рейтинг пользователя (простое среднее оценок, которые ему поставили другие) —
его репутация, и она же усиливает или ослабляет его голос за места. Поэтому
репутацию выгодно накручивать подставными аккаунтами. Две защиты, обе простые:
  * оценить пользователя можно только после посещения его места (см. views);
  * в вес голоса рейтинг входит не «как есть», а сглаженным к нейтральному
    значению: пока оценок мало, он почти не отличается от нейтрального, и чтобы
    заметно поднять вес, нужно много оценок, а не одна-две от своих людей.
"""

NEUTRAL_RATING = 3.0    # «нет данных»: у неоценённого пользователя вес ровно 1
TRUST_PRIOR_VOTES = 3   # столько «воображаемых» оценок NEUTRAL_RATING добавляем к настоящим
WEIGHT_STEP = 0.25      # прибавка к весу за каждую звезду выше (или ниже) нейтральной


def trusted_rating(rating, ratings_count):
    """Рейтинг, которому доверяем при расчёте веса: среднее, сглаженное к нейтральному.

    Оценки «5» дают: одна — 3,5, пять — 4,25, десять — 4,5, тридцать — 4,8."""
    if not ratings_count or rating <= 0:
        return NEUTRAL_RATING
    return (TRUST_PRIOR_VOTES * NEUTRAL_RATING + rating * ratings_count) / (TRUST_PRIOR_VOTES + ratings_count)


def vote_weight(rater_rating, ratings_count=None):
    """Вес голоса пользователя при оценке места: от 0,5 (рейтинг 1) до 1,5 (рейтинг 5).

    Неоценённый пользователь (рейтинг 0) весит ровно 1 — столько же, сколько
    «средний», а не больше, чем тот, кого оценили низко. ratings_count — сколько
    оценок получил голосующий; если он известен, рейтинг сглаживается
    (см. trusted_rating). Без него рейтинг берётся как есть."""
    if ratings_count is None:
        trusted = rater_rating if rater_rating > 0 else NEUTRAL_RATING
    else:
        trusted = trusted_rating(rater_rating, ratings_count)
    return 1 + WEIGHT_STEP * (trusted - NEUTRAL_RATING)
