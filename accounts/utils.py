def vote_weight(rater_rating):
    """Вес голоса пользователя при оценке грибного места.

    Линейно растёт с рейтингом того, кто голосует: 1x при рейтинге 0,
    3x при максимальном рейтинге 5. Так мнение проверенных, хорошо
    оценённых пользователей весит больше, но новички не исключаются
    полностью.
    """
    return 1 + 0.4 * rater_rating
